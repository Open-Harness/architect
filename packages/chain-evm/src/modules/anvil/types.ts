import type { Effect, Redacted, Scope } from "effect";
import { Data } from "effect";
import type { Timers } from "@orthograph/language-effect";
import type { Address, Hex } from "viem";

export class AnvilFailed extends Data.TaggedError("AnvilFailed")<{
  readonly message: string;
}> {}

/** A funded test account the world made itself. The key is redacted: it prints as `<redacted>` and is read with `Redacted.value`. */
export interface TestAccount {
  readonly address: Address;
  readonly privateKey: Redacted.Redacted<Hex>;
}

export interface AnvilOptions {
  /** Default 31337. */
  readonly chainId?: number;
  /** Default: a free loopback port the OS picks. */
  readonly port?: number;
  /** How many funded accounts to make. Default 3. */
  readonly accounts?: number;
  /** Each account's balance in wei. Default 10_000 ether. */
  readonly balance?: bigint;
  /** Whole seconds between blocks. Default: none, Anvil mines a block for each transaction. A world that wants depth sets it, so blocks come without a transaction. */
  readonly blockTime?: number;
  /** The Anvil binary. Default: `anvil` on PATH. */
  readonly binary?: string;
}

export interface RunningAnvil {
  readonly rpcUrl: string;
  readonly chainId: number;
  readonly pid: number;
  /** Funded accounts with keys generated by the world, never by Anvil. */
  readonly accounts: ReadonlyArray<TestAccount>;
  /** Everything Anvil wrote to stdout or stderr. `--silent` makes it empty. */
  readonly printed: () => string;
}

export interface AnvilApi {
  /**
   * Run Anvil as a process of this scope: always `--silent`, on loopback, with no dev accounts of its own. The world
   * makes the keys and funds them over RPC, so no key is in an argument, an environment variable, a file or any output.
   * Ready once `eth_chainId` answers; killed, and waited for, when the scope closes.
   */
  readonly start: (options?: AnvilOptions) => Effect.Effect<RunningAnvil, AnvilFailed, Scope.Scope | Timers>;
}
