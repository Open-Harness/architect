import { mkdirSync, mkdtempSync, realpathSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterAll, describe, expect, it } from "vitest";
import { ServerConfig } from "./service.ts";

const base = `// Generated from the blueprint. Do not edit.
{
  "name": "acme",
  "main": "main.ts",
  "d1_databases": [
    { "binding": "DB", "database_name": "acme", "database_id": "0", "migrations_dir": "migrations" },
    { "binding": "DB_LEDGER", "database_name": "acme-ledger", "database_id": "1", "migrations_dir": "migrations/ledger" }
  ],
  "vars": { "OTLP_URL": "http://x//y" } // a trailing comment
}
`;

const temp = mkdtempSync(join(realpathSync(tmpdir()), "server-config-"));
afterAll(() => rmSync(temp, { recursive: true, force: true }));

describe("derive", () => {
  it("makes main and the migrations folders absolute, and keeps everything else as it was", () => {
    const text = ServerConfig.derive("/p", base, undefined);
    expect(text.split("\n")[0]).toBe("// Generated by ortho from generated/server/wrangler.jsonc. Do not edit.");
    const config = ServerConfig.parse(text) as Record<string, unknown>;
    expect(config).toMatchObject({ name: "acme", main: "/p/generated/server/main.ts", vars: { OTLP_URL: "http://x//y" } });
    expect((config["d1_databases"] as Array<{ migrations_dir: string }>).map((d) => d.migrations_dir)).toEqual(["/p/generated/server/migrations", "/p/generated/server/migrations/ledger"]);
    expect(config).not.toHaveProperty("assets");
  });

  it("with the portal's client, binds it as static assets the Worker answers before", () => {
    const config = ServerConfig.parse(ServerConfig.derive("/p", base, "/client")) as { assets: unknown };
    expect(config.assets).toEqual({ directory: "/client", binding: "PORTAL_ASSETS", run_worker_first: true });
  });
});

describe("clientOf", () => {
  const project = (built: boolean) => {
    const root = mkdtempSync(join(temp, "project-"));
    const portal = mkdtempSync(join(temp, "portal-"));
    writeFileSync(join(root, "package.json"), "{}");
    writeFileSync(join(portal, "package.json"), JSON.stringify({ name: "@orthograph/portal", exports: { "./package.json": "./package.json" } }));
    if (built) { mkdirSync(join(portal, "dist/client"), { recursive: true }); writeFileSync(join(portal, "dist/client/index.html"), "<!doctype html>"); }
    mkdirSync(join(root, "node_modules/@orthograph"), { recursive: true });
    symlinkSync(portal, join(root, "node_modules/@orthograph/portal"));
    return { root, portal };
  };

  it("is the built client of the portal the project resolves, and nothing when it is not built", () => {
    const built = project(true);
    expect(ServerConfig.clientOf(built.root)).toBe(join(built.portal, "dist/client"));
    expect(ServerConfig.clientOf(project(false).root)).toBeUndefined();
  });
});
